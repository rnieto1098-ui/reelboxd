type TitleYearEntry = { title: string; year: number };

const DIACRITIC_MARKS = /[̀-ͯ]/g;

function normalizeTitle(s: string) {
  return s
    .toLowerCase()
    .normalize("NFKD")
    .replace(DIACRITIC_MARKS, "")
    .replace(/[^a-z0-9]+/g, " ")
    .trim();
}

// A result whose title doesn't match can still be trusted if it's clearly a
// real, notable movie (an alternate/translated title TMDB stores under a
// different `title` string — e.g. "Nausicaä of the Valley of the Wind" is
// stored as "Warriors of the Wind", its old US release title). Below this
// vote count, an unmatched-title year hit is far more often TMDB's search
// returning some unrelated obscure film that happens to share the release
// year than it is a genuine alternate title.
const MIN_VOTES_FOR_TITLE_MISMATCH = 30;

function closeEnoughYear(m: { release_date: string }, year: number, tolerance: number) {
  const resultYear = Number(m.release_date?.slice(0, 4));
  return Number.isFinite(resultYear) && Math.abs(resultYear - year) <= tolerance;
}

// Resolves a single title+year to a TMDB movie, preferring precision over
// coverage: an entry that can't be matched with confidence is left
// unresolved (and simply excluded from the seeded list) rather than guessing,
// since a wrong movie silently injected into the list is worse than a gap.
async function resolveOne({ title, year }: TitleYearEntry) {
  const target = normalizeTitle(title);

  // TMDB's `primary_release_year` filter has weak text relevance on its own —
  // querying "Kes" + 1969 surfaces Butch Cassidy and the Sundance Kid (same
  // year, nothing to do with the query) ahead of the real "Kes". So a
  // year-filtered hit is only trusted when the title also matches; anything
  // looser is deferred to the unfiltered search below, which is an actual
  // text match on the query.
  const withYear = await searchMovies(title, 1, year).catch(() => null);
  const withYearExact = withYear?.results.find((m) => normalizeTitle(m.title) === target);
  if (withYearExact) return withYearExact;

  // Some entries' TMDB primary_release_year doesn't match the year given
  // (e.g. a qualifying limited release one year, wide release the next), so
  // the year-filtered search can come up empty even though the movie is
  // right there. Fall back to an unfiltered title search.
  let unfiltered = await searchMovies(title).catch(() => null);

  // TMDB's search can return nothing at all for a long, punctuation-heavy
  // title (e.g. "Jeanne Dielman, 23, quai du Commerce, 1080 Bruxelles"
  // matches zero results as a full string). Retry against just the part
  // before the first comma.
  if (!unfiltered?.results.length && title.includes(",")) {
    unfiltered = await searchMovies(title.split(",")[0].trim()).catch(() => null);
  }

  if (!unfiltered?.results.length) return null;

  // Require the year too, not just the title: some titles are shared by
  // multiple unrelated films decades apart (there's a "Le Bonheur" from 1934
  // *and* the 1965 Agnès Varda film everyone means) — an exact title match
  // alone isn't enough to know which one the source list is pointing at. The
  // tolerance is wider than the untitled fallback below (2 years vs. 1)
  // since an exact title match is already strong evidence on its own — e.g.
  // "Hundreds of Beavers" premiered at festivals in 2022 but TMDB's
  // primary_release_year is 2024, its wide release.
  const exact = unfiltered.results.find(
    (m) => normalizeTitle(m.title) === target && closeEnoughYear(m, year, 2)
  );
  if (exact) return exact;

  // No exact title match anywhere — accept a same-year, well-known result as
  // a probable alternate/translated title (e.g. "Nausicaä of the Valley of
  // the Wind" is stored on TMDB as "Warriors of the Wind", its old US
  // release title). The vote-count bar exists to reject the far more common
  // case: an unrelated, obscure film that just happens to share the year.
  const trusted = unfiltered.results.find(
    (m) => closeEnoughYear(m, year, 1) && (m.vote_count ?? 0) >= MIN_VOTES_FOR_TITLE_MISMATCH
  );
  return trusted ?? null;
}

// Resolves a title+year list to TMDB movies, preserving input order. Runs in
// small concurrent batches rather than firing every request at once — large
// lists (500+ entries, up to 2 requests each) were seeing spurious misses
// under full concurrency.
async function resolveTitleYearList(entries: TitleYearEntry[]) {
  const BATCH_SIZE = 20;
  const movies: (Awaited<ReturnType<typeof resolveOne>>)[] = [];

  for (let i = 0; i < entries.length; i += BATCH_SIZE) {
    const batch = entries.slice(i, i + BATCH_SIZE);
    const batchResults = await Promise.all(batch.map(resolveOne));
    movies.push(...batchResults);
  }

  const seenTmdbIds = new Set<number>();
  const result: { movie: NonNullable<(typeof movies)[number]>; year: number }[] = [];
  for (let i = 0; i < movies.length; i++) {
    const movie = movies[i];
    // A higher-ranked entry that already claimed this TMDB id wins; this can
    // happen when two different source titles both fall back to matching the
    // same movie. Drop the later (lower-ranked) duplicate rather than letting
    // it violate the list's (listId, tmdbId) uniqueness constraint.
    if (!movie || seenTmdbIds.has(movie.id)) continue;
    seenTmdbIds.add(movie.id);
    result.push({ movie, year: entries[i].year });
  }
  return result;
}

