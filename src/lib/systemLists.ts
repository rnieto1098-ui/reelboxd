// Once this process has confirmed every system list exists, it never stops
// being true — skips a `findMany` that would otherwise run on every single
// homepage/lists page view for the rest of the server's lifetime.
let allSystemListsConfirmed = false;

export async function ensureSystemLists() {
  if (allSystemListsConfirmed) return;

  const existing = await prisma.list.findMany({
    where: { key: { in: SYSTEM_LIST_KEYS } },
    select: { key: true },
  });
  const existingKeys = new Set(existing.map((l) => l.key));

  if (!existingKeys.has(OSCAR_LIST_KEY)) await seedOscarList();
  if (!existingKeys.has(LETTERBOXD_LIST_KEY)) await seedLetterboxdTop500List();
  if (!existingKeys.has(IMDB_LIST_KEY)) await seedImdbTop250List();
  if (!existingKeys.has(CANNES_LIST_KEY)) await seedCannesList();
  if (!existingKeys.has(TSPDT_LIST_KEY)) await seedTspdtList();
  if (!existingKeys.has(MOVIES_1001_LIST_KEY)) await seedMovies1001List();
  if (!existingKeys.has(UNDERSEEN_100_LIST_KEY)) await seedUnderseenList();
  if (!existingKeys.has(SCIFI_250_LIST_KEY)) await seedSciFiList();
  if (!existingKeys.has(MOST_FANS_250_LIST_KEY)) await seedMostFansList();
  if (!existingKeys.has(MYSTERY_250_LIST_KEY)) await seedMysteryList();
  if (!existingKeys.has(HORROR_250_LIST_KEY)) await seedHorrorList();
  if (!existingKeys.has(WAR_250_LIST_KEY)) await seedWarList();

  allSystemListsConfirmed = true;
}

export type ListCard = {
  id: string;
  title: string;
  coverPosterPath: string | null;
  coverImage: string | null;
  itemCount: number;
};

export async function getHomepageListCards(userId: string | undefined): Promise<ListCard[]> {
  await ensureSystemLists();

  const lists = await prisma.list.findMany({
    where: userId ? { OR: [{ isSystem: true }, { ownerId: userId }] } : { isSystem: true },
    orderBy: [{ isSystem: "desc" }, { createdAt: "asc" }],
    include: {
      _count: { select: { items: true } },
      items: { take: 1, orderBy: { position: "asc" } },
    },
  });

  const personalCovers = await getPersonalListCoverMap(
    userId,
    lists.map((list) => list.id)
  );

  return lists.map((list) => ({
    id: list.id,
    title: list.title,
    coverPosterPath: list.items[0]?.posterPath ?? null,
    coverImage: personalCovers.get(list.id) ?? list.coverImage,
    itemCount: list._count.items,
  }));
}

export type ListProgress = {
  id: string;
  title: string;
  itemCount: number;
  watchedCount: number;
  percent: number;
};

function parseCuratedListOrder(raw: string | null | undefined): string[] {
  return raw ? raw.split(",").filter(Boolean) : [];
}

// A rating anywhere in this app means "watched" — same convention as every
// per-list watched-percent badge, just computed for every curated list at
// once instead of one at a time.
export async function getCuratedListsProgress(
  userId: string | undefined,
  watchedTmdbIds: Set<number>
): Promise<ListProgress[]> {
  if (!userId) return [];
  await ensureSystemLists();

  const [lists, user] = await Promise.all([
    prisma.list.findMany({
      where: { isSystem: true },
      select: { id: true, title: true, items: { select: { tmdbId: true } } },
    }),
    prisma.user.findUnique({ where: { id: userId }, select: { curatedListOrder: true } }),
  ]);

  const progress = lists.map((list) => {
    const itemCount = list.items.length;
    const watchedCount = list.items.filter((item) => watchedTmdbIds.has(item.tmdbId)).length;
    return {
      id: list.id,
      title: list.title,
      itemCount,
      watchedCount,
      percent: itemCount > 0 ? Math.round((watchedCount / itemCount) * 100) : 0,
    };
  });

  const savedOrder = parseCuratedListOrder(user?.curatedListOrder);
  if (savedOrder.length === 0) {
    // No custom order saved yet — same default as before this feature
    // existed, so a user who's never touched the reorder controls sees no
    // change.
    return progress.sort((a, b) => b.percent - a.percent);
  }

  // Anything the user has already placed keeps that order; a curated list
  // added since they last reordered (something with no saved position)
  // falls back to percent-desc and is appended after the ones they placed.
  const positionById = new Map(savedOrder.map((id, i) => [id, i]));
  const ordered = progress
    .filter((p) => positionById.has(p.id))
    .sort((a, b) => positionById.get(a.id)! - positionById.get(b.id)!);
  const unordered = progress
    .filter((p) => !positionById.has(p.id))
    .sort((a, b) => b.percent - a.percent);
  return [...ordered, ...unordered];
}

// Persists the signed-in user's preferred display order for their "Your
// List Progress" cards. Filtered against the real set of system list ids
// so a stale or tampered id can't sneak an arbitrary string into the
// column — anything not recognized is silently dropped rather than
// rejecting the whole save.
export async function setCuratedListOrder(userId: string, orderedIds: string[]): Promise<void> {
  const validIds = new Set(
    (await prisma.list.findMany({ where: { isSystem: true }, select: { id: true } })).map((l) => l.id)
  );
  const cleaned = orderedIds.filter((id) => validIds.has(id));
  await prisma.user.update({
    where: { id: userId },
    data: { curatedListOrder: cleaned.join(",") },
  });
}
