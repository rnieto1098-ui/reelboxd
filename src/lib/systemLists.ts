// Claims a system list's row via its unique `key` *before* doing any TMDB
// resolution work. Two requests racing to seed the same list for the first
// time (e.g. concurrent page loads) both pass the "does this exist" check at
// nearly the same time — without this, both would spend a minute resolving
// 500 movies and then both insert, producing duplicates. Whichever loses the
// unique-constraint race here bails out immediately instead.
async function claimSystemList(key: string, title: string, description: string) {
  try {
    return await prisma.list.create({ data: { key, title, description, isSystem: true } });
  } catch (e) {
    if (e instanceof Prisma.PrismaClientKnownRequestError && e.code === "P2002") return null;
    throw e;
  }
}

